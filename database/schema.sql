-- ESTRUCTURA DE BASE DE DATOS - POSTGRESQL
-- ==============================================

CREATE TABLE public.rol (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(50) NOT NULL,
    CONSTRAINT rol_pkey PRIMARY KEY (id_rol),
    CONSTRAINT rol_nombre_key UNIQUE (nombre)
);

CREATE TABLE public.usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY,
    usuario VARCHAR(50) NOT NULL,
    password VARCHAR(255) NOT NULL,
    estado CHAR(1) NOT NULL DEFAULT 'A',
    id_rol INTEGER NOT NULL,
    CONSTRAINT usuario_pkey PRIMARY KEY (id_usuario),
    CONSTRAINT usuario_usuario_key UNIQUE (usuario),
    CONSTRAINT usuario_estado_check
        CHECK (estado IN ('A', 'I')),
    CONSTRAINT usuario_id_rol_fkey
        FOREIGN KEY (id_rol) REFERENCES public.rol(id_rol)
);

CREATE TABLE public.productos (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    precio NUMERIC(12,2) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    estado CHAR(1) NOT NULL DEFAULT 'A',
    CONSTRAINT productos_pkey PRIMARY KEY (id_producto),
    CONSTRAINT ck_productos_estado
        CHECK (estado IN ('A', 'I')),
    CONSTRAINT productos_nombre_check
        CHECK (BTRIM(nombre) <> ''),
    CONSTRAINT productos_precio_check
        CHECK (precio >= 0),
    CONSTRAINT productos_stock_check
        CHECK (stock >= 0)
);
